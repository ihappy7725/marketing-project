/* 보유 재료로 만들 수 있는 메뉴를 점수순으로 반환 */
function sodamMatch(have, limit) {
  return SODAM_RECIPES.map(function (r) {
    return {
      r: r,
      hit: r.needs.filter(function (n) { return have.indexOf(n) !== -1; }),
      missing: r.needs.filter(function (n) { return have.indexOf(n) === -1; })
    };
  }).filter(function (m) {
    return m.hit.length > 0;
  }).sort(function (a, b) {
    var ra = a.hit.length / a.r.needs.length, rb = b.hit.length / b.r.needs.length;
    if (rb !== ra) { return rb - ra; }
    if (b.hit.length !== a.hit.length) { return b.hit.length - a.hit.length; }
    return a.missing.length - b.missing.length;
  }).slice(0, limit || 3);
}
